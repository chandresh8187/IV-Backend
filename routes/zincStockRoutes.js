const router = require('express').Router();
const auth = require('../middleware/authMiddleware');
const access = require('../middleware/roleMiddleware');
const { getZincStock, getAverageZincRate, getRateCalculatorContext, getZincMovements, downloadZincMovementsPdf, saveZincMovement } = require('../controllers/zincStockController');
const { updateByproduct, createByproduct, getByproducts, downloadByproductsPdf } = require('../controllers/zincByproductController');
const { getPurchases, updatePurchase, downloadPurchasesPdf } = require('../controllers/zincPurchaseController');
router.use(auth);
router.get('/', access([], 'zinc_stock.view'), getZincStock);
router.get('/average-rate', access([], 'rate_calculator.view'), getAverageZincRate);
router.get('/rate-calculator-context', access([], 'rate_calculator.view'), getRateCalculatorContext);
router.get('/transfer-context', access([], 'zinc_stock.transfer'), getZincStock);
router.get('/movements', access([], 'zinc_stock.view'), getZincMovements);
router.get('/movements/pdf', access([], 'zinc_stock.report'), downloadZincMovementsPdf);
router.post('/movements', saveZincMovement);
router.get('/purchases', access([], 'zinc_stock.view'), getPurchases);
router.get('/purchases/pdf', access([], 'zinc_stock.report'), downloadPurchasesPdf);
router.post('/purchases', access([], 'zinc_stock.receive'), (req, res) => { req.body = { ...req.body, action: 'receive' }; return saveZincMovement(req, res); });
router.put('/purchases/:id', access([], 'zinc_stock.receive'), updatePurchase);
router.get('/byproducts', access([], 'zinc_stock.view'), getByproducts);
router.post('/byproducts', access([], 'zinc_byproduct.manage'), createByproduct);
router.put('/byproducts/:id', access([], 'zinc_byproduct.manage'), updateByproduct);
router.get('/byproducts/pdf', access([], 'zinc_stock.report'), downloadByproductsPdf);
module.exports = router;
